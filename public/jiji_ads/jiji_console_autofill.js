window.postAd = function(id) {
  const ad = window.JIJI_ADS.find(a => a.id === id);
  if (!ad) {
    console.error('Ad not found. Use id 1 to 10. E.g.: postAd(1)');
    return;
  }

  // 1. Fill Title
  const titleInput = document.querySelector('input[name="title"], input[placeholder*="Title" i], input[data-qa="title-input"]');
  if (titleInput) {
    titleInput.value = ad.title;
    titleInput.dispatchEvent(new Event('input', { bubbles: true }));
    titleInput.dispatchEvent(new Event('change', { bubbles: true }));
    console.log('✅ Title populated:', ad.title);
  }

  // 2. Fill Price
  const priceInput = document.querySelector('input[name="price"], input[type="number"], input[data-qa="price-input"]');
  if (priceInput) {
    priceInput.value = ad.price;
    priceInput.dispatchEvent(new Event('input', { bubbles: true }));
    priceInput.dispatchEvent(new Event('change', { bubbles: true }));
    console.log('✅ Price populated:', ad.price);
  }

  // 3. Fill Description
  const descTextarea = document.querySelector('textarea[name="description"], textarea, textarea[data-qa="description-input"]');
  if (descTextarea) {
    descTextarea.value = ad.desc;
    descTextarea.dispatchEvent(new Event('input', { bubbles: true }));
    descTextarea.dispatchEvent(new Event('change', { bubbles: true }));
    console.log('✅ Description populated');
  }

  // 4. Copy to clipboard as fallback
  navigator.clipboard.writeText(ad.desc);
  console.log('📋 Full description copied to clipboard!');
  console.log(`🖼️ Now upload picture: C:\\Users\\HomePC\\Desktop\\JIJI_ADS_PICTURES\\ad_${ad.id}_...`);
  alert(`Ad #${ad.id} populated! Description copied to clipboard. Now drag the matching picture from your Desktop folder: JIJI_ADS_PICTURES!`);
};

console.log('🚀 Jiji Auto-Filler Loaded! Type postAd(1) to post Ad 1, postAd(2) for Ad 2, etc.');

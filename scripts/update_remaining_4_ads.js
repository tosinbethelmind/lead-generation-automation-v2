async function updateRemainingAds() {
  const config = JSON.parse(fs.readFileSync('local_db/jiji_account_config.json', 'utf8'));
  const browser = await chromium.launch({
    headless: true,
    executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    args: ['--disable-blink-features=AutomationControlled', '--no-sandbox']
  });
  const context = await browser.newContext({
    userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/133.0.0.0 Safari/537.36',
    viewport: { width: 1280, height: 1000 }
  });
  await context.route('**/*', (route) => {
    const req = route.request();
    const type = req.resourceType();
    const url = req.url();
    if (['image', 'media', 'font'].includes(type) || url.includes('google-analytics') || url.includes('facebook') || url.includes('clarity') || url.includes('criteo')) {
      return route.abort();
    }
    return route.continue();
  });
  const validCookies = (config.cookiesJson || []).map(c => {
    const copy = { ...c };
    if (!['Strict', 'Lax', 'None'].includes(copy.sameSite)) delete copy.sameSite;
    return copy;
  });
  await context.addCookies(validCookies);

  const page = await context.newPage();
  const summary = [];

  for (let i = 0; i < REMAINING_ADS.length; i++) {
    const ad = REMAINING_ADS[i];
    console.log(`\n============================================================`);
    console.log(`[${i + 1}/${REMAINING_ADS.length}] Processing Ad #${ad.adId}: ${ad.title}`);
    console.log(`Edit URL: ${ad.editUrl}`);
    console.log(`============================================================`);

    try {
      await page.goto(ad.editUrl, { waitUntil: 'domcontentloaded', timeout: 45000 });
      await page.waitForTimeout(4000);

      // 1. Wait for title input
      const titleInput = await page.waitForSelector('input[name="title"]', { timeout: 8000 }).catch(() => null);

      if (titleInput) {
        console.log('-> Step 1 active: Updating Title...');
        await titleInput.fill(ad.title);
        await titleInput.dispatchEvent('input');
        await titleInput.dispatchEvent('change');
        await page.waitForTimeout(1000);

        // Upload banner if file input exists
        const imgPath = path.resolve(__dirname, `../public/jiji_ads/${ad.imageFile}`);
        const fileInput = await page.$('input[type="file"]');
        if (fileInput && fs.existsSync(imgPath)) {
          console.log(`-> Uploading luxury banner: ${ad.imageFile}...`);
          await fileInput.setInputFiles(imgPath);
          await page.waitForTimeout(3000);
        }

        // Click Next button
        const nextBtn = await page.$('button.b-create-ad-card__next-button');
        if (nextBtn) {
          console.log('-> Clicking Next button with force: true...');
          await nextBtn.click({ force: true });
          await page.waitForTimeout(4000);
        }
      }

      // 2. Wait for description textarea on Step 2
      await page.waitForSelector('textarea[name="description"]', { timeout: 8000 }).catch(() => null);

      // Update Price and Description
      console.log('-> Updating Price and Description...');
      const priceInput = await page.$('input.qa-enter-price, input[name="price"][type="text"]');
      if (priceInput) {
        await priceInput.fill(ad.price);
        await priceInput.dispatchEvent('input');
        await priceInput.dispatchEvent('change');
        console.log(`   Price set to NGN ${ad.price}`);
      }

      const descInput = await page.$('textarea[name="description"]');
      if (descInput) {
        await descInput.fill(ad.desc);
        await descInput.dispatchEvent('input');
        await descInput.dispatchEvent('change');
        console.log('   Description updated');
      }
      await page.waitForTimeout(2000);

      // Submit
      console.log('-> Submitting ad update to Jiji...');
      const submitBtn = await page.$('button.b-create-ad-card__submit-button, button.qa-submit-button, #submit_button, #boost_premium_1_button');
      if (submitBtn) {
        await submitBtn.click({ force: true });
        await page.waitForTimeout(7000);
        const finalUrl = page.url();
        console.log(`✔ Ad #${ad.adId} submitted! Result URL: ${finalUrl}`);
        summary.push({ adId: ad.adId, title: ad.title, status: 'SUCCESS', finalUrl });
      } else {
        console.warn(`⚠ Submit button not found for Ad #${ad.adId}`);
        summary.push({ adId: ad.adId, title: ad.title, status: 'NO_SUBMIT_BUTTON' });
      }

      await page.screenshot({ path: `local_db/updated_ad_${ad.adId}.png` });

    } catch (err) {
      console.error(`❌ Error updating Ad #${ad.adId}:`, err.message);
      summary.push({ adId: ad.adId, title: ad.title, status: 'ERROR', error: err.message });
    }

    console.log('Waiting 5s before next ad...');
    await page.waitForTimeout(5000);
  }

  fs.writeFileSync('local_db/jiji_remaining_report.json', JSON.stringify(summary, null, 2), 'utf8');
  console.log('\n============================================================');
  console.log('REMAINING 4 ADVERTS UPDATE COMPLETED:');
  console.log(JSON.stringify(summary, null, 2));
  console.log('============================================================');

  await browser.close();
}

updateRemainingAds().catch(console.error);

async function updateAllAds() {
  const config = JSON.parse(fs.readFileSync('local_db/jiji_account_config.json', 'utf8'));
  const browser = await chromium.launch({
    headless: true,
    executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',
    args: ['--disable-blink-features=AutomationControlled', '--no-sandbox']
  });
  const context = await browser.newContext({
    userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/133.0.0.0 Safari/537.36',
    viewport: { width: 1280, height: 1000 }
  });
  await context.addInitScript(() => {
    Object.defineProperty(navigator, 'webdriver', { get: () => undefined });
  });

  const validCookies = (config.cookiesJson || []).map(c => {
    const copy = { ...c };
    if (!['Strict', 'Lax', 'None'].includes(copy.sameSite)) delete copy.sameSite;
    return copy;
  });
  await context.addCookies(validCookies);

  const page = await context.newPage();

  console.log(`Starting automated updates for ${LIVE_ADS_UPDATE_DECK.length} live Jiji adverts...\n`);

  const results = [];

  for (let i = 0; i < LIVE_ADS_UPDATE_DECK.length; i++) {
    const ad = LIVE_ADS_UPDATE_DECK[i];
    console.log(`============================================================`);
    console.log(`[${i + 1}/${LIVE_ADS_UPDATE_DECK.length}] Updating Ad #${ad.adId}`);
    console.log(`Title (${ad.title.length}/70 chars): "${ad.title}"`);
    console.log(`Price: ₦${ad.price}`);
    console.log(`URL: ${ad.editUrl}`);
    console.log(`============================================================`);

    try {
      await page.goto(ad.editUrl, { waitUntil: 'networkidle', timeout: 35000 });
      await page.waitForTimeout(3000);

      // 1. STEP 1: TITLE
      console.log('-> Step 1: Updating Title...');
      await page.fill('input[name="title"]', ad.title);
      await page.waitForTimeout(1000);

      // 2. STEP 1: UPLOAD 2D LUXURY IMAGE
      const luxuryImgPath = path.resolve(__dirname, `../public/jiji_ads/${ad.imageFile}`);
      const fileInput = await page.$('input[type="file"].qa-messenger-send-image, input[type="file"]');
      if (fileInput && fs.existsSync(luxuryImgPath)) {
        console.log(`-> Uploading 2D luxury banner (${ad.imageFile})...`);
        await fileInput.setInputFiles(luxuryImgPath);
        await page.waitForTimeout(4000);
      }

      // 3. STEP 1: CLICK NEXT
      console.log('-> Clicking Next button...');
      const nextBtn = await page.$('.b-create-ad-card__next-button, button:has-text("Next")');
      if (nextBtn) {
        await nextBtn.click();
        await page.waitForTimeout(3000);
      }

      // 4. STEP 2: PRICE & DESCRIPTION
      console.log('-> Step 2: Updating Price & Description...');
      const priceInput = await page.$('input.qa-enter-price, input[name="price"][type="text"]');
      if (priceInput) {
        await priceInput.fill(ad.price);
        console.log(`   ✔ Price set to ₦${ad.price}`);
      }

      const descInput = await page.$('textarea[name="description"]');
      if (descInput) {
        await descInput.fill(ad.desc);
        console.log('   ✔ Description populated');
      }

      await page.waitForTimeout(2000);

      // 5. STEP 2: SUBMIT / POST AD
      const submitBtn = await page.$('#submit_button, button.qa-submit-button, button[type="submit"]');
      if (submitBtn) {
        const isEnabled = await submitBtn.isEnabled();
        console.log(`-> Submit button enabled: ${isEnabled}`);
        if (isEnabled) {
          console.log('-> Submitting changes to Jiji...');
          await submitBtn.click();
          await page.waitForTimeout(6000);
          console.log(`✔ Ad #${ad.adId} successfully updated! Post-submit URL: ${page.url()}`);
          results.push({ adId: ad.adId, title: ad.title, status: 'SUCCESS', finalUrl: page.url() });
        } else {
          console.warn(`⚠ Submit button disabled for Ad #${ad.adId}`);
          results.push({ adId: ad.adId, title: ad.title, status: 'BUTTON_DISABLED' });
        }
      }

      // Save screenshot for audit verification
      await page.screenshot({ path: `local_db/updated_ad_${ad.adId}.png` });

    } catch (err) {
      console.error(`❌ Error updating Ad #${ad.adId}:`, err.message);
      results.push({ adId: ad.adId, title: ad.title, status: 'ERROR', error: err.message });
    }

    // Gentle jitter delay between edits to prevent rate limiting
    console.log('Waiting 5s before next advert...\n');
    await page.waitForTimeout(5000);
  }

  fs.writeFileSync('local_db/jiji_live_updates_report.json', JSON.stringify(results, null, 2), 'utf8');
  console.log('\n============================================================');
  console.log('--- ALL LIVE JIJI ADVERTS UPDATED SUCCESSFULLY ---');
  console.log(JSON.stringify(results, null, 2));
  console.log('============================================================');

  await browser.close();
}

updateAllAds().catch(console.error);
